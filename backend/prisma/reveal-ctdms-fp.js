async function run() {
  // Find all masked CTDMS vehicles still in DB with FP blocking
  const masked = await prisma.vehicle.findMany({
    where: {
      chassisNumber: { startsWith: 'MBJAAXXXXXXXXX' },
      stockStatus: 'CTDMS',
      blockings: { some: { status: 'ACTIVE', paymentStatus: 'Full Payment Received' } },
    },
    select: { chassisNumber: true },
  });

  if (!masked.length) {
    console.log('No masked CTDMS vehicles with FP blocking found.');
    await prisma.$disconnect();
    return;
  }

  console.log(`Found ${masked.length} masked CTDMS vehicle(s) with FP:\n`);
  let revealed = 0, noMapping = 0, conflict = 0;

  for (const v of masked) {
    const real = MAP[v.chassisNumber];
    if (!real) {
      console.log(`NO MAPPING: ${v.chassisNumber} — provide real VIN`);
      noMapping++;
      continue;
    }
    try {
      await prisma.vehicle.update({ where: { chassisNumber: v.chassisNumber }, data: { chassisNumber: real } });
      console.log(`REVEALED: ${v.chassisNumber} → ${real}`);
      revealed++;
    } catch (e) {
      if (e.code === 'P2002') {
        console.log(`CONFLICT (real VIN exists): ${real} — skipping ${v.chassisNumber}`);
        conflict++;
      } else { throw e; }
    }
  }

  console.log(`\nRevealed: ${revealed} | No mapping: ${noMapping} | Conflict: ${conflict}`);
  await prisma.$disconnect();
}

run().catch(e => { console.error(e); process.exit(1); });
