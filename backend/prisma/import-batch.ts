function parseDate(d: string): Date {
  const [day, month, year] = d.split('/').map(Number);
  return new Date(Date.UTC(year, month - 1, day));
}

function hardBlockExpiryFrom(baseDate: Date, days: number): Date {
  const IST = 5.5 * 60 * 60 * 1000;
  const baseIst = new Date(baseDate.getTime() + IST);
  const mid = Date.UTC(baseIst.getUTCFullYear(), baseIst.getUTCMonth(), baseIst.getUTCDate() + days);
  return new Date(mid - IST + 23 * 60 * 60 * 1000);
}

