async function main() {
  const branches = await prisma.branch.findMany({ select: { id: true, branchCode: true } });
  const branchByCode = new Map(branches.map(b => [b.branchCode, b.id]));

  // preload one SM per branch
  const sms = await prisma.user.findMany({
    where: { role: 'SALES_MANAGER' },
    select: { id: true, branchId: true },
  });
  const smByBranch = new Map<string, string>();
  for (const sm of sms) {
    if (sm.branchId && !smByBranch.has(sm.branchId)) smByBranch.set(sm.branchId, sm.id);
  }

  let created = 0, skipped = 0, warned = 0;

  for (const row of ROWS) {
    const [stockyard, model, suffix, colour, chassisNumber, chassisYear, stockStatus, assignmentDateStr, blockedBranch, orderId, customerName] = row;

    const physBranchId = branchByCode.get(stockyard as string);
    const blockedBranchId = branchByCode.get(blockedBranch as string);

    if (!physBranchId || !blockedBranchId) {
      console.log(`⚠️  Unknown branch for ${chassisNumber} (${stockyard}→${blockedBranch})`);
      warned++; continue;
    }

    const smId = smByBranch.get(blockedBranchId);
    if (!smId) {
      console.log(`⚠️  No SM found for branch ${blockedBranch} (${chassisNumber})`);
      warned++; continue;
    }

    const assignmentDate = parseDate(assignmentDateStr as string);
    const expiryAt = hardBlockExpiryFrom(assignmentDate, 30);

    const vehicle = await prisma.vehicle.upsert({
      where: { chassisNumber: chassisNumber as string },
      update: { model: model as string, suffix: suffix as string, colour: colour as string, chassisYear: chassisYear as number, stockStatus: (stockStatus as string) as any, stockyardLocation: stockyard as string, physicalStockBranchId: physBranchId, assignmentDate, status: 'HARD_BLOCKED' as any },
      create: { chassisNumber: chassisNumber as string, model: model as string, suffix: suffix as string, colour: colour as string, chassisYear: chassisYear as number, stockStatus: (stockStatus as string) as any, stockyardLocation: stockyard as string, physicalStockBranchId: physBranchId, assignmentDate, status: 'HARD_BLOCKED' as any },
    });

    const existing = await prisma.blockingRequest.findFirst({ where: { vehicleId: vehicle.id, status: 'ACTIVE' } });
    if (existing) { skipped++; continue; }

    await prisma.blockingRequest.create({
      data: {
        vehicleId: vehicle.id,
        userId: smId,
        branchId: blockedBranchId,
        blockType: 'HARD',
        status: 'ACTIVE',
        softBlockAt: assignmentDate,
        hardBlockAt: assignmentDate,
        expiryAt,
        orderId: String(orderId),
        customerName: String(customerName).trim(),
      },
    });
    created++;
    process.stdout.write(`✅ ${chassisNumber}\n`);
  }

  console.log(`\nDone: ${created} created, ${skipped} skipped (already blocked), ${warned} warnings`);
  await prisma.$disconnect();
}

main().catch(e => { console.error(e); prisma.$disconnect(); process.exit(1); });
