async function main() {
  // Find all matching vehicles
  const vehicles = await prisma.vehicle.findMany({
    where: { chassisNumber: { in: CHASSIS } },
    select: { id: true, chassisNumber: true },
  });

  const vehicleIds = vehicles.map((v) => v.id);
  const found = vehicles.map((v) => v.chassisNumber);
  const notFound = CHASSIS.filter((c) => !found.includes(c));

  console.log(`Found: ${vehicleIds.length} vehicles`);
  if (notFound.length) console.log(`Not found (${notFound.length}): ${notFound.slice(0, 20).join(', ')}${notFound.length > 20 ? '...' : ''}`);

  if (vehicleIds.length === 0) { console.log('Nothing to delete.'); await prisma.$disconnect(); return; }

  // Delete blockings first (FK constraint), then vehicles
  const delBlockings = await prisma.blockingRequest.deleteMany({ where: { vehicleId: { in: vehicleIds } } });
  const delVehicles  = await prisma.vehicle.deleteMany({ where: { id: { in: vehicleIds } } });

  console.log(`✅ Deleted ${delBlockings.count} blocking(s) and ${delVehicles.count} vehicle(s)`);
  await prisma.$disconnect();
}

main().catch((e) => { console.error(e); prisma.$disconnect(); process.exit(1); });
